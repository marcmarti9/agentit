#!/usr/bin/env python3
"""Build one portable entry from the exact three owned core bodies.

This is documentation materialization, not an installer or semantic router.
No network, upstream scripts, profile bodies or private state are included.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORE = ("using-agentit", "task-router", "using-agent-skills")


def render(root: Path = ROOT) -> str:
    parts = [
        "# Use Agentit — portable entry\n\n"
        "Read this entire file before material work when asked to use Agentit. "
        "It contains the three complete core skill bodies and profile purpose pointers; "
        "domain skill bodies remain just in time.\n\n"
        "Agentit is a library of operating instructions and expertise. "
        "Use it through your authorized file/repository reader in an ordinary chat, "
        "or through an installed coding-agent adapter. Installation is optional. "
        "User instructions and host safety/permissions take precedence.\n\n"
        "1. Read all three bodies below completely.\n"
        "2. Match the task to the profile pointers; open "
        "[the unified profile index](references/agentit-profile-index.md).\n"
        "3. Read selected skill files completely, then apply their procedures to the task.\n"
        "4. Check artifacts and outcomes; disclose missing file/tool access.\n\n"
        "Paths in these bodies are relative to the repository root. With a web or "
        "GitHub reader, resolve them against the same repository revision. "
        "If this file is uploaded by itself, linked domain skills are not included: "
        "retrieve them through an authorized reader or have their full content supplied. "
        "Do not pretend a link, search result, upload or receipt proves a read.\n\n"
        "Generated by `python3 scripts/build_chat_entry.py`; edit the canonical "
        "core sources, then regenerate. Hashes below describe exact UTF-8 source bytes "
        "and detect drift; they are not signatures or model-compliance proof.\n\n"
    ]
    for skill_id in CORE:
        relative = f"skills/{skill_id}/SKILL.md"
        path = root / relative
        if path.is_symlink():
            raise ValueError(f"core source cannot be a symlink: {relative}")
        data = path.read_bytes()
        body = data.decode("utf-8")
        if not body.strip():
            raise ValueError(f"empty core source: {relative}")
        parts.append(
            f"## Complete core: {skill_id}\n\n"
            f"Source: `{relative}` · bytes: {len(data)} · "
            f"SHA-256: `{hashlib.sha256(data).hexdigest()}`\n\n"
            f"<!-- core-body:{skill_id}:start -->\n{body}"
            f"\n<!-- core-body:{skill_id}:end -->\n\n"
        )
    return "".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    target = ROOT / "AGENTIT.md"
    expected = render().encode("utf-8")
    if target.is_symlink():
        parser.error("AGENTIT.md must not be a symlink")
    if args.check:
        if not target.is_file() or target.read_bytes() != expected:
            parser.exit(1, "AGENTIT.md is stale; run python3 scripts/build_chat_entry.py\n")
        print("Portable entry matches the complete canonical core.")
    else:
        target.write_bytes(expected)
        print(f"Wrote AGENTIT.md ({len(expected)} bytes).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
