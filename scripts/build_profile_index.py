#!/usr/bin/env python3
"""Generate portable profile pointers and body links; fail on drift or uncovered IDs.

No model task routing or skill activation occurs here. Profiles are authored
domain metadata. Estimated context cost is UTF-8 body bytes / 4, not tokenization.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from router.profiles import ProfileError, load_catalog, resolve_profile
from router.skills_cli import SkillDiscoveryError, list_profiles, skill_metadata
from router.ecc import ECCError

START = "<!-- profile-pointers:start -->"
END = "<!-- profile-pointers:end -->"


def validate_coverage(catalog: dict, metadata: dict) -> None:
    covered = set()
    for profile_id, profile in catalog["profiles"].items():
        resolved = set(resolve_profile(profile_id, catalog))
        missing = resolved - metadata.keys()
        if missing:
            raise SkillDiscoveryError(f"profile {profile_id} references missing skills: {', '.join(sorted(missing))}")
        if not profile.get("description"):
            raise SkillDiscoveryError(f"profile {profile_id} has no purpose description")
        if profile_id != "all" and not profile.get("compatibility_alias"):
            covered.update(resolved)
    uncovered = metadata.keys() - covered
    if uncovered:
        raise SkillDiscoveryError("canonical skills without a domain profile: " + ", ".join(sorted(uncovered)))
    if set(resolve_profile("all", catalog)) != metadata.keys():
        raise SkillDiscoveryError("all must resolve to exactly the canonical skill inventory")


def pointer_block(items: list[dict]) -> str:
    lines = [START, "| If you need to... | Inspect profile metadata |", "| --- | --- |"]
    for item in items:
        lines.append(f"| {item['use_for']} | `{item['id']}` |")
    lines.extend(["", "Each ID points to its matching section in [references/agentit-profile-index.md](references/agentit-profile-index.md), relative to the Agentit repository root. CLI: `agentit skills candidates --profile ID`. These pointers activate no bodies.", END])
    return "\n".join(lines)


def render_index(root: Path, catalog: dict, metadata: dict, items: list[dict]) -> str:
    lines = ["# Agentit profile index", "", "Generated by `python3 scripts/build_profile_index.py`; edit `profiles.yaml`, then regenerate. `--check` fails on drift, unknown IDs or canonical skills without a meaningful domain profile.", "", "Profiles are source-neutral availability/discovery maps. Agentit-authored and imported skills share these domains; provenance stays in each source path. Compatibility aliases appear last and never define a second catalog.", "", "Choose profiles from the actual task, inspect metadata, then explicitly select complete bodies. A profile never activates itself. Select a subset by relevance; a whole profile is justified only when every body helps the current stage and the context cost fits. Neither a fixed minimum nor a fixed maximum applies.", "", "Body cost includes inherited skills once per profile. Estimated tokens = UTF-8 bytes / 4, rounded up per body; this is a rough planning heuristic, not a tokenizer count. Supporting references and host instructions add context beyond these estimates.", "", "| Profile | Use for | Skills incl. inherited | Body bytes | Estimated tokens |", "| --- | --- | ---: | ---: | ---: |"]
    for item in items:
        lines.append(f"| [{item['id']}](#{item['id']}) | {item['use_for']} | {item['skill_count']} | {item['body_bytes']} | ~{item['estimated_tokens']} |")
    lines += ["", "## Profile contents", "", "The following links are direct assignments; follow parent profile links for inherited skills. Reading this index delivers metadata, not the linked skill bodies."]
    indexed = {item["id"]: item for item in list_profiles(include_aliases=True, repo_root=root, catalog=catalog)}
    for profile_id, profile in catalog["profiles"].items():
        if profile.get("compatibility_alias"):
            continue
        lines += ["", f"## {profile_id}", "", indexed[profile_id]["use_for"], ""]
        parents = profile.get("extends", [])
        if parents:
            lines += ["Inherits: " + ", ".join(f"[{name}](#{name})" for name in parents) + ".", ""]
        lines += [f"Inspect metadata: `agentit skills candidates --profile {profile_id}`. Use `--direct` to omit inherited skills.", ""]
        for skill_id in profile.get("skills", []):
            item = metadata[skill_id]
            lines.append(f"- [{skill_id}](../{item['path']}) — {item['description']}")
        if not profile.get("skills"):
            lines.append("This profile is the union of its parent profiles; it adds no direct bodies.")
    lines += ["", "## Compatibility aliases", "", "Existing installation IDs remain valid. New selections should use the domains above; `agentit skills profiles --include-aliases` exposes these aliases explicitly.", ""]
    for profile_id, profile in catalog["profiles"].items():
        if profile.get("compatibility_alias"):
            lines.append(f"- `{profile_id}` → " + ", ".join(f"[{name}](#{name})" for name in profile.get("extends", [])) + ".")
    return "\n".join(lines) + "\n"


def build(root: Path, *, check: bool) -> list[str]:
    catalog = load_catalog(root / "profiles.yaml")
    metadata = skill_metadata(root)
    validate_coverage(catalog, metadata)
    items = list_profiles(repo_root=root, catalog=catalog)
    core = root / "skills/using-agentit/SKILL.md"
    core_text = core.read_text(encoding="utf-8")
    if core_text.count(START) != 1 or core_text.count(END) != 1:
        raise SkillDiscoveryError("core must have exactly one profile pointer marker pair")
    pattern = re.compile(re.escape(START) + ".*?" + re.escape(END), re.DOTALL)
    expected_core = pattern.sub(lambda _: pointer_block(items), core_text)
    drift = []
    if expected_core != core_text:
        drift.append(core.relative_to(root).as_posix())
        if not check:
            core.write_text(expected_core, encoding="utf-8")
            # Core body costs must describe the generated bytes, not the old marker block.
            metadata = skill_metadata(root)
            items = list_profiles(repo_root=root, catalog=catalog)
    index = root / "references/agentit-profile-index.md"
    expected_index = render_index(root, catalog, metadata, items)
    if not index.exists() or index.read_text(encoding="utf-8") != expected_index:
        drift.append(index.relative_to(root).as_posix())
        if not check:
            index.write_text(expected_index, encoding="utf-8")
    return drift


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        drift = build(args.repo, check=args.check)
    except (SkillDiscoveryError, ProfileError, ECCError, OSError, UnicodeError) as exc:
        parser.error(str(exc))
    if args.check and drift:
        print("profile discovery drift: " + ", ".join(drift), file=sys.stderr)
        return 1
    print("profile discovery: " + ("updated " + ", ".join(drift) if drift else "coverage and generated pointers are current"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
